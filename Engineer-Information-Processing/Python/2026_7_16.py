#이 문제는 파이썬 가변 기본 인자(Mutable Default Argument)의 함정을 보여주는 예제이다.
def func(a, b=[]):
    b.append(a)
    return b

print(func(1))
print(func(2))
print(func(3, [10, 20]))
#func(1) 호출 시 b는 함수 정의 시점에 딱 한 번 생성된 빈 리스트 []를 참조 -> append(1) -> [1] 반환
#func(2) 호출 시에도 b는 기본값을 다시 만들지 않고, 이전 호출에서 쓰인 "같은" 리스트 객체를 재사용함 -> [1, 2] 반환
#func(3, [10, 20]) 호출 시에는 b에 새 리스트 [10, 20]을 직접 전달했으므로 기본값과 무관하게 append(3) -> [10, 20, 3] 반환
#출력 결과는 [1] / [1, 2] / [10, 20, 3] 이렇게 세 줄이다.
#기본 인자로 리스트처럼 변경 가능한(mutable) 객체를 쓰면, 호출할 때마다 새로 초기화되는 게 아니라 계속 누적된다는 함정을 조심하자!
